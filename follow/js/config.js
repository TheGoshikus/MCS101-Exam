/*
 * Настройки лендинга Follow.
 * Всё, что нужно поменять перед запуском, находится здесь.
 */
window.FOLLOW_CONFIG = {
  // Адрес сервера сбора данных (follow/server/server.js).
  // '' — тот же домен, откуда открыт лендинг (когда страницу раздаёт сам сервер).
  // null — сервера нет: записи сохраняются только в localStorage этого браузера (режим отладки).
  apiBase: location.protocol === 'file:' ? null : '',

  // Номер счётчика Яндекс Метрики. Если указан — подключается Метрика с Вебвизором,
  // картой кликов и целями на каждую кнопку. null — Метрика не подключается.
  metrikaId: null,

  // true — запись сессии начинается только после нажатия «Принять» в плашке про cookies.
  // false — запись идёт сразу, плашка носит информационный характер.
  requireConsent: false,

  // Хранить записи в localStorage посетителя (удобно для локальной проверки без сервера).
  // По умолчанию включено только когда сервера нет.
  localRecordings: location.protocol === 'file:',

  // Ограничения записи
  maxDurationMs: 30 * 60 * 1000, // не дольше 30 минут на одну страницу
  maxEvents: 30000,
  flushIntervalMs: 3000
};
